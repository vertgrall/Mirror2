//! OSD burn-in — camcorder date stamp, CCTV timestamp.

use chrono::Local;

use super::ops::lerp_u8;

/// Frozen camcorder date — nostalgia, not a clock.
pub const GX_DATE: &str = "MAR 14 1994";

pub fn burn_gx_stamp(rgba: &mut [u8], w: u32, h: u32, opacity: f32) {
    if opacity < 0.01 {
        return;
    }
    let rec = "● REC";
    let y0 = h.saturating_sub(28);
    draw_string(rgba, w, h, 12, y0, GX_DATE, (255, 240, 200), opacity);
    draw_string(rgba, w, h, 12, y0 + 14, rec, (255, 60, 60), opacity * 0.9);
}

pub fn burn_cctv_stamp(rgba: &mut [u8], w: u32, h: u32, frame: u64) {
    let blink = (frame / 15) % 2 == 0;
    if !blink {
        return;
    }
    let text = Local::now().format("%m/%d/%Y %H:%M:%S").to_string();
    draw_string(rgba, w, h, 8, 8, &text, (80, 255, 120), 0.85);
}

/// Frozen MiniDV date — digital tape, not a clock.
pub const D8_DATE: &str = "JAN 01 2000";

pub fn burn_d8_date(rgba: &mut [u8], w: u32, h: u32, opacity: f32) {
    if opacity < 0.01 {
        return;
    }
    draw_string(rgba, w, h, w.saturating_sub(108), 8, D8_DATE, (240, 240, 255), opacity);
}

fn draw_string(
    rgba: &mut [u8],
    w: u32,
    h: u32,
    x0: u32,
    y0: u32,
    text: &str,
    color: (u8, u8, u8),
    opacity: f32,
) {
    let mut x = x0;
    for ch in text.chars() {
        draw_char(rgba, w, h, x, y0, ch, color, opacity);
        x += 8;
    }
}

fn draw_char(
    rgba: &mut [u8],
    w: u32,
    h: u32,
    x0: u32,
    y0: u32,
    ch: char,
    color: (u8, u8, u8),
    opacity: f32,
) {
    let glyph = glyph_5x7(ch);
    for (row, bits) in glyph.iter().enumerate() {
        for col in 0..5 {
            if bits & (1 << (4 - col)) != 0 {
                let x = x0 + col as u32;
                let y = y0 + row as u32;
                if x < w && y < h {
                    let i = ((y * w + x) as usize) * 4;
                    rgba[i] = lerp_u8(rgba[i], color.0, opacity);
                    rgba[i + 1] = lerp_u8(rgba[i + 1], color.1, opacity);
                    rgba[i + 2] = lerp_u8(rgba[i + 2], color.2, opacity);
                }
            }
        }
    }
}

fn glyph_5x7(ch: char) -> [u8; 7] {
    match ch {
        '0'..='9' => digit(ch as u8 - b'0'),
        'A'..='Z' => letter(ch as u8 - b'A'),
        'a'..='z' => letter((ch as u8 - b'a') + b'A' - b'A'),
        ' ' => [0; 7],
        '●' => [0x0, 0x0, 0x4, 0xE, 0x4, 0x0, 0x0],
        '/' => [0x2, 0x4, 0x8, 0x10, 0x0, 0x0, 0x0],
        ':' => [0x0, 0x4, 0x0, 0x4, 0x0, 0x0, 0x0],
        _ => [0x1F, 0x11, 0x1F, 0x0, 0x0, 0x0, 0x0],
    }
}

